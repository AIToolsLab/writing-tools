import { describe, it, expect } from 'vitest';
import { isValidElement, type ReactNode } from 'react';
import scenarios from '@/lib/scenarios.json';
import { introSurveySections, getPostTaskSurveySections } from '@/components/survey/surveyData';
import type { Question } from '@/components/survey/types';

// The log viewer (scripts/log-viewer.html) opens from disk with no build step,
// so it can't import the survey or scenario definitions. This test generates
// scripts/log-viewer/study-materials.js from them and fails if the checked-in
// copy is out of date. Regenerate with:
//   npx vitest run __tests__/scripts/studyMaterials.test.ts -u

function plainText(node: ReactNode): string {
  if (node == null || typeof node === 'boolean') return '';
  if (typeof node === 'string' || typeof node === 'number') return String(node);
  if (Array.isArray(node)) return node.map(plainText).join('');
  if (isValidElement<{ children?: ReactNode; className?: string }>(node)) {
    const inner = plainText(node.props.children);
    return /\bblock\b/.test(node.props.className ?? '') ? `\n${inner}\n` : inner;
  }
  return '';
}

const tidy = (s: string) => s.replace(/[ \t]+\n/g, '\n').replace(/\n{3,}/g, '\n\n').trim();

function questionInfo(q: Question, section: string) {
  return {
    id: q.id,
    section,
    type: q.type,
    text: tidy(plainText(q.text)),
    ...(q.options ? { options: q.options } : {}),
  };
}

function buildMaterials() {
  const aiIds = new Set(
    getPostTaskSurveySections('complete_document', 'roomDoubleBooking')
      .flatMap((s) => s.questions.map((q) => q.id))
      .filter((id) => !getPostTaskSurveySections('no_ai', 'roomDoubleBooking').some((s) => s.questions.some((q) => q.id === id))),
  );
  return {
    scenarios: Object.fromEntries(
      Object.entries(scenarios).map(([id, sc]) => [
        id,
        {
          colleague: sc.colleague.name,
          recipient: sc.recipient.name,
          taskTitle: sc.taskInstructions.title,
          taskDescription: sc.taskInstructions.description,
          context: sc.analysis?.context ?? '',
          // Post-task questions as shown in an AI condition; `aiOnly` ones are skipped in no_ai.
          postTask: getPostTaskSurveySections('complete_document', id).flatMap((s) =>
            s.questions.map((q) => ({ ...questionInfo(q, s.title), ...(aiIds.has(q.id) ? { aiOnly: true } : {}) })),
          ),
        },
      ]),
    ),
    intro: introSurveySections.flatMap((s) => s.questions.map((q) => questionInfo(q, s.title))),
  };
}

describe('log viewer study materials', () => {
  it('scripts/log-viewer/study-materials.js matches the survey and scenario definitions', async () => {
    const body = JSON.stringify(buildMaterials(), null, 1);
    const file = `// GENERATED by __tests__/scripts/studyMaterials.test.ts from components/survey/surveyData.tsx
// and lib/scenarios.json. Do not edit. Regenerate:
//   npx vitest run __tests__/scripts/studyMaterials.test.ts -u
(function (root) {
  const STUDY_MATERIALS = ${body};
  if (typeof module === 'object' && module.exports) module.exports = STUDY_MATERIALS;
  else root.STUDY_MATERIALS = STUDY_MATERIALS;
})(this);
`;
    await expect(file).toMatchFileSnapshot('../../scripts/log-viewer/study-materials.js');
  });
});
